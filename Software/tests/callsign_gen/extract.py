#!/usr/bin/env python3
"""Copies getRandomCall(), getRandomPrefix(), buildRandomPrefix() and their helpers verbatim out of m32_v6.ino into extracted.inc, so the host
program compiles the SAME code the M32 runs (the Makefile re-runs this when m32_v6.ino changes)."""
import pathlib, re, sys

SRC = pathlib.Path(__file__).resolve().parents[2] / 'src' / 'Version 6 and newer'
ino = (SRC / 'm32_v6.ino').read_text(encoding='utf-8', errors='surrogateescape')

def block(start_re):
    m = re.search(start_re, ino, re.M)
    if not m:
        sys.exit('extract.py: not found in m32_v6.ino: ' + start_re)
    i, depth, j, seen = m.start(), 0, m.start(), False
    while j < len(ino):
        if ino[j] == '{': depth += 1; seen = True
        elif ino[j] == '}':
            depth -= 1
            if seen and depth == 0:
                return ino[i:ino.find('\n', j) + 1]
        elif ino[j] == ';' and not seen:
            return ino[i:j + 1] + '\n'
        j += 1
    sys.exit('extract.py: unbalanced braces after ' + start_re)

parts = ['// GENERATED by extract.py from m32_v6.ino -- do not edit\n',
         block(r'^static void readPrefix\('),
         block(r'^static char pickAreaDigit\('),
         block(r'^static uint8_t getContinentMask\('),
         block(r'^uint8_t lastGeneratedCallContinent'),
         block(r'^uint8_t lastGeneratedCallCqZone'),
         block(r'^static int buildRandomPrefix\('),
         block(r'^String getRandomCall\('),
         block(r'^String getRandomPrefix\(')]
pathlib.Path(__file__).with_name('extracted.inc').write_text(''.join(parts), encoding='utf-8', errors='surrogateescape')
print('extracted.inc written')
