#!/usr/bin/env python3
"""Copies the firmware's cw/play text path out of m32_v6.ino into extracted.inc, verbatim, so the
host test compiles the SAME code the M32 runs (re-run it after every firmware change -- the Makefile
does). Pulled by name: the CW tables, the Koch character string, and the functions from the protocol
buffer to the element string."""
import pathlib, re, sys

SRC = pathlib.Path(__file__).resolve().parents[2] / 'src' / 'Version 6 and newer'
ino = (SRC / 'm32_v6.ino').read_text(encoding='utf-8', errors='surrogateescape')
prefs = (SRC / 'MorsePreferences.h').read_text(encoding='utf-8', errors='surrogateescape')

def block(start_re, text=ino):
    """From the line matching start_re to its closing brace (or to the ';' of a one-statement table)."""
    m = re.search(start_re, text, re.M)
    if not m:
        sys.exit('extract.py: not found in the firmware: ' + start_re)
    i = m.start()
    depth, j, seen = 0, i, False
    while j < len(text):
        c = text[j]
        if c == '{': depth += 1; seen = True
        elif c == '}':
            depth -= 1
            if seen and depth == 0:
                k = text.find('\n', j)
                return text[i:k + 1 if k >= 0 else len(text)]
        elif c == ';' and not seen:
            return text[i:j + 1] + '\n'
        j += 1
    sys.exit('extract.py: unbalanced braces after ' + start_re)

koch = re.search(r'morserinoKochChars\s*=\s*("[^"]*")', prefs)
if not koch:
    sys.exit('extract.py: morserinoKochChars not found')

parts = [
    '// GENERATED by extract.py from m32_v6.ino and MorsePreferences.h -- do not edit\n',
    'struct { const char* const morserinoKochChars = %s; } koch;\n' % koch.group(1),
    block(r'^const char CWchars\[\]'),
    block(r'^const byte pool\[\]\[2\]'),
    block(r'^int indexOfConstStr\('),
    block(r'^String generateCWword\('),
    block(r'^static const char\* foldLatin1\('),
    block(r'^String utf8umlaut\('),
    block(r'^String cleanUpText\('),
    block(r'^String getM32PWord\('),
    block(r'^boolean playCWHasMore\('),
]
out = ''.join(parts)
out = re.sub(r'\bB([01]{1,8})\b', r'0b\1', out)          # Arduino's binary.h constants
pathlib.Path(__file__).with_name('extracted.inc').write_text(out, encoding='utf-8', errors='surrogateescape')
print('extracted.inc: %d lines' % out.count('\n'))
