#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
make_inventories.py -- regenerate the machine-derived inventories.

Writes, next to this script:
  inventory-menu-terms.md   on-device labels used in the manual, with the
                            firmware gating that says whether they differ
                            between variants
  inventory-images.md       image references and their variant classification
  inventory-tables.md       every table, with the properties session 2 needs
                            to decide which ones to linearise for the a11y build
  inventory-morse.md        every occurrence of Morse written as symbols

inventory-ambiguous.md is deliberately NOT generated: it is a judgement
document and is maintained by hand.

Usage:  python3 make_inventories.py
"""
import os
import re
from collections import Counter

import firmware_terms as ft
import tagmap

HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = ("en", "de")


def sources():
    return {l: open(os.path.join(tagmap.MANUAL, "manual_%s.md" % l),
                    encoding="utf-8").read().split("\n") for l in LANGS}


def section_at(sections, line):
    best = None
    for s in sections:
        if s["line"] <= line:
            best = s
        else:
            break
    return best["title"] if best else "(front matter)"


def find_term(lines, term):
    """Line numbers where the term appears as a device label.

    The manual marks device labels in bold or italics most of the time, but not
    always, so plain occurrences count too -- with a word boundary so that
    'Random' does not match 'Randomly'.

    Matched against the *joined* text rather than line by line, because the
    German source wraps at ~72 characters and splits terms across lines
    ("*Upload\\nFile*"). A line-by-line search silently misses those and makes
    the two languages look divergent when they are not.
    """
    words = [re.escape(w) for w in term.split()]
    pat = re.compile(r"(?<![A-Za-z0-9])" + r"[\s*_]+".join(words)
                     + r"(?![A-Za-z0-9])")
    text = "\n".join(lines)
    starts, pos = [], 0
    for line in lines:
        starts.append(pos)
        pos += len(line) + 1

    def line_of(idx):
        lo, hi = 0, len(starts) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if starts[mid] <= idx:
                lo = mid
            else:
                hi = mid - 1
        return lo + 1

    return sorted({line_of(m.start()) for m in pat.finditer(text)})


# ---------------------------------------------------------------- menu terms
def menu_terms(src):
    rows = []
    seen = set()
    groups = (("menu entry", [(t, g) for t, g in ft.menu_entries()]),
              ("preference", [(t, g) for t, _, g in ft.preferences()]),
              ("action item", [(t, g) for t, g in ft.extra_items()]))
    for kind, items in groups:
        for term, guards in items:
            key = (kind, term)
            if key in seen:
                continue
            seen.add(key)
            variants = ft.variants_for(guards)
            hits = {l: find_term(src[l], term) for l in LANGS}
            rows.append({"kind": kind, "term": term, "guards": guards,
                         "variants": variants, "hits": hits})
    # option values that differ per variant are the interesting ones
    values = []
    per_label = {}
    for label, opts, guards in ft.preferences():
        per_label.setdefault(label, []).append((opts, guards))
    for label, variants in per_label.items():
        if len(variants) > 1:
            values.append((label, variants))
    return rows, values


def write_menu_terms(src):
    rows, differing_values = menu_terms(src)
    out = []
    w = out.append
    w("# Inventory: on-device terms used in the manual\n")
    w("Generated by `make_inventories.py`. Do not edit by hand.\n")
    w("Every menu entry, preference label and action item the firmware defines,")
    w("with the build flags that gate it and the lines of each manual where the")
    w("string occurs. **Nothing here is changed yet** -- session 2 introduces the")
    w("placeholder mechanism that resolves these from a per-variant terminology")
    w("file; this is the list it has to cover.\n")
    w("The variant column comes from the firmware's own `#ifdef`s, not from the")
    w("prose, so it is the authority when the two disagree.\n")

    flagged = [r for r in rows if len(r["variants"]) < 3]
    w("## Terms that do NOT exist on every variant (%d)\n" % len(flagged))
    w("These are the ones a per-variant terminology file has to handle. A term")
    w("with no manual hits is not documented at all -- also worth knowing.\n")
    w("| Kind | Term | Exists on | Gated by | EN lines | DE lines |")
    w("|---|---|---|---|---|---|")
    for r in sorted(flagged, key=lambda r: (r["kind"], r["term"])):
        w("| %s | `%s` | %s | `%s` | %s | %s |"
          % (r["kind"], r["term"], ", ".join(r["variants"]),
             ", ".join(r["guards"]) or "-",
             ", ".join(map(str, r["hits"]["en"])) or "*not documented*",
             ", ".join(map(str, r["hits"]["de"])) or "*not documented*"))
    w("")

    if differing_values:
        w("## Preferences whose option *values* differ per variant (%d)\n"
          % len(differing_values))
        w("Same label on both devices, different set of choices behind it --")
        w("the case a naive label-only terminology file would miss.\n")
        for label, variants in differing_values:
            w("**`%s`**\n" % label)
            for opts, guards in variants:
                w("- on %s (`%s`): %s"
                  % (", ".join(ft.variants_for(guards)),
                     ", ".join(guards) or "-",
                     ", ".join("`%s`" % o for o in opts) if opts
                     else "*values not on a single source line; check by hand*"))
            w("")

    universal = [r for r in rows if len(r["variants"]) == 3]
    undocumented = [r for r in universal if not r["hits"]["en"]]
    w("## Terms present on every variant (%d)\n" % len(universal))
    w("No terminology entry needed. Listed for completeness, and because the")
    w("ones with no manual hits are undocumented device labels.\n")
    w("| Kind | Term | EN lines | DE lines |")
    w("|---|---|---|---|")
    for r in sorted(universal, key=lambda r: (r["kind"], r["term"])):
        w("| %s | `%s` | %s | %s |"
          % (r["kind"], r["term"],
             ", ".join(map(str, r["hits"]["en"][:8]))
             + (" …" if len(r["hits"]["en"]) > 8 else "") or "*not documented*",
             ", ".join(map(str, r["hits"]["de"][:8]))
             + (" …" if len(r["hits"]["de"]) > 8 else "") or "*not documented*"))
    w("")
    w("%d of these never appear in the English manual: %s.\n"
      % (len(undocumented),
         ", ".join("`%s`" % r["term"] for r in undocumented) or "none"))
    return "\n".join(out)


